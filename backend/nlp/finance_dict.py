def lexicon_score(text: str) -> float:
    """基于金融词典的情感打分，返回 -1.0 ~ 1.0"""
    score = 0.0
    hits = 0
    for word, w in POSITIVE_WORDS.items():
        if word in text:
            score += w
            hits += 1
    for word, w in NEGATIVE_WORDS.items():
        if word in text:
            score += w
            hits += 1
    if hits == 0:
        return 0.0
    # 归一化到 [-1, 1]
    return max(-1.0, min(1.0, score / (hits * 2.0)))
